import { Teammate } from '../types';

export type NodeType = 'SCENARIO' | 'ROLEPLAY' | 'COACH_PRACTICE' | 'REVIEW' | 'CHALLENGE';

export interface ScenarioChoice {
  text: string;
  quality: 'optimal' | 'neutral' | 'poor';
  scoreBonus: number;
  aiResponse: string;
  empathyImpact: number;
  communicationImpact: number;
  ownershipImpact: number;
  problemSolvingImpact: number;
}

export interface ScenarioTurn {
  id: number;
  guestLine: string;
  guestEmotion: string;
  coachAdvice: string;
  choices: ScenarioChoice[];
}

export interface ScenarioData {
  id: string;
  levelNumber: number;
  levelLabel: string;
  unitId: string;
  unitTitle: string;
  unitNumber: string;
  nodeType: NodeType;
  title: string;
  department: string;
  difficulty: 1 | 2 | 3 | 4 | 5;
  estimatedTime: string;
  xpReward: number;
  primarySkill: 'Empathy' | 'Communication' | 'Ownership' | 'Problem Solving' | 'Guest Focus';
  description: string;
  guestName: string;
  guestRole: string;
  situationSummary: string;
  turns: ScenarioTurn[];
}

export interface UnitData {
  id: string;
  number: string;
  title: string;
  subtitle: string;
  atmosphere: string;
  icon: string;
  scenarios: ScenarioData[];
}

